/** Human-readable language name from file extension (for status bar / tab labels) */
export function getLanguageFromFileName(fileName: string): string {
  const ext = fileName.split('.').pop()?.toLowerCase();
  const map: Record<string, string> = {
    ts: 'TypeScript',
    tsx: 'TypeScript (JSX)',
    js: 'JavaScript',
    jsx: 'JavaScript (JSX)',
    mjs: 'JavaScript',
    cjs: 'JavaScript',
    py: 'Python',
    json: 'JSON',
    jsonl: 'JSON Lines',
    css: 'CSS',
    scss: 'SCSS',
    sass: 'Sass',
    less: 'Less',
    html: 'HTML',
    htm: 'HTML',
    xml: 'XML',
    svg: 'SVG',
    md: 'Markdown',
    mdx: 'MDX',
    markdown: 'Markdown',
    yaml: 'YAML',
    yml: 'YAML',
    rs: 'Rust',
    go: 'Go',
    java: 'Java',
    c: 'C',
    h: 'C/C++ Header',
    cpp: 'C++',
    cxx: 'C++',
    cc: 'C++',
    hpp: 'C++ Header',
    php: 'PHP',
    sql: 'SQL',
    sh: 'Shell',
    bash: 'Bash',
    zsh: 'Zsh',
    toml: 'TOML',
    ini: 'INI',
    conf: 'Config',
    txt: 'Plain Text',
  };
  return map[ext ?? ''] ?? 'Plain Text';
}
