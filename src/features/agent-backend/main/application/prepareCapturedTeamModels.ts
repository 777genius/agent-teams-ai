import { createHash, randomUUID } from 'node:crypto';
import { resolve } from 'node:path';
import { setTimeout as delay } from 'node:timers/promises';

import { capturedTeamSelectionSignature } from '@shared/utils/capturedTeamReadiness';
import { isDefaultProviderModelSelection } from '@shared/utils/providerModelSelection';

import type { BackendHandle } from '../../contracts';
import type {
  BackendLaunchConfigurationView,
  BackendLaunchModelProbe,
  BackendLaunchModelSelection,
} from '../../contracts/launch';
import type { AgentBackendApi } from '../../contracts/operations';
import type { TeamModelProbeIntents } from './TeamModelProbeIntents';
import type {
  TeamProviderId,
  TeamProvisioningModelCheckRequest,
  TeamProvisioningPrepareResult,
} from '@shared/types/team';

export interface CapturedTeamModelRequest {
  cwd?: string;
  providerId?: TeamProviderId;
  providerIds?: TeamProviderId[];
  modelIds?: string[];
  modelChecks?: TeamProvisioningModelCheckRequest[];
  /** Full desired choices survive the existing diagnostics' cached/runtime-only call. */
  selectedModelChecks?: TeamProvisioningModelCheckRequest[];
  limitContext?: boolean;
  /** One existing-dialog opening/explicit refresh; never regenerated by a render. */
  preparationId?: string;
}

type ModelView = Pick<BackendLaunchConfigurationView, 'members'> & {
  launch: { launchId: string; rosterRevision: string };
};

const unavailable = (message: string): TeamProvisioningPrepareResult => ({
  ready: false,
  message,
});
function commandId(handle: BackendHandle, selection: BackendLaunchModelSelection): string {
  // This is a single check of one captured launch selection, including across reload.
  // The Host's existing durable probe journal owns all outcomes. No second journal.
  return `team-preflight-${createHash('sha256')
    .update(JSON.stringify([handle.handleId, selection]))
    .digest('hex')}`;
}
function checkKey(check: TeamProvisioningModelCheckRequest): string {
  return JSON.stringify([check.providerId, check.model, check.effort ?? null]);
}
function configurationFingerprint(view: ModelView): string {
  // Every real Host read advances observation time without changing the selection.
  return JSON.stringify({
    ...view,
    launch: { ...view.launch, observedAtMs: undefined },
  });
}

/** Existing dialog model preflight. Never allocates member sessions or reads fork/global defaults. */
export async function prepareCapturedTeamModels(options: {
  backend: Pick<AgentBackendApi, 'invoke'>;
  handle: BackendHandle;
  request: CapturedTeamModelRequest;
  isCurrent(): boolean;
  wait?: () => Promise<unknown>;
  intents?: TeamModelProbeIntents;
}): Promise<TeamProvisioningPrepareResult> {
  const handle = { ...options.handle };
  const request = structuredClone(options.request);
  const alive = () => {
    try {
      return options.isCurrent() === true;
    } catch {
      return false;
    }
  };
  const active = new Map<string, BackendLaunchModelSelection>();
  const completed: BackendLaunchModelProbe[] = [];
  const wait = options.wait ?? (() => delay(200));
  const invoke = (
    action: 'start' | 'read' | 'cancel',
    selection: BackendLaunchModelSelection,
    id: string
  ) =>
    options.backend.invoke({
      handle,
      commandId: id,
      operation: `team.launch.probe.${action}`,
      payload: selection,
    });
  async function readConfiguration(): Promise<ModelView> {
    if (!alive()) throw new Error('Team context changed.');
    const result = await options.backend.invoke({
      handle,
      commandId: randomUUID(),
      operation: 'team.launch.model.configuration.read',
      payload: {},
    });
    if (!alive()) throw new Error('Team context changed.');
    if (!result.ok || !result.value || !('source' in result.value) || !('members' in result.value))
      throw new Error('Captured Team launch settings are unavailable.');
    const view = result.value;
    return {
      launch: {
        launchId: view.source.sourceId,
        rosterRevision: view.source.rosterRevision,
      },
      members: view.members,
    };
  }
  try {
    if (request.preparationId && !options.intents)
      return unavailable('Captured Team check intent storage is unavailable.');
    const view = await readConfiguration();
    const members = view.members.filter((member) => member.selected !== null);
    const providerId = (provider: 'claude' | 'codex' | 'opencode'): TeamProviderId =>
      provider === 'claude' ? 'anthropic' : provider;
    const leads = view.members.filter((member) => member.role === 'lead');
    if (
      !members.length ||
      members.length !== view.members.length ||
      !request.cwd ||
      leads.length !== 1 ||
      !leads[0]!.selected
    )
      return unavailable('Captured Team member settings are unavailable.');
    const supplied: TeamProvisioningModelCheckRequest[] =
      request.modelChecks ??
      (request.modelIds ?? []).map((model) => ({
        providerId: request.providerId ?? providerId(leads[0]!.selected!.provider),
        model,
      }));
    const choices = request.selectedModelChecks ?? supplied;
    if (supplied.some((check) => !choices.some((choice) => checkKey(check) === checkKey(choice))))
      return unavailable('Model checks do not match the original dialog selection.');
    const targeted = choices.some((choice) => choice.targets !== undefined);
    if (
      !targeted &&
      (resolve(leads[0]!.selected!.workspace) !== resolve(request.cwd) ||
        (request.providerId !== undefined &&
          request.providerId !== providerId(leads[0]!.selected!.provider)) ||
        (!request.modelChecks &&
          request.modelIds?.length &&
          new Set(members.map((member) => member.selected!.provider)).size > 1))
    )
      return unavailable('The edited providers or workspace require explicit member destinations.');
    type Planned = {
      memberId: string;
      saved: NonNullable<ModelView['members'][number]['selected']> | undefined;
      choice?: TeamProvisioningModelCheckRequest;
      draft?: BackendLaunchModelSelection['draft'];
    };
    const planned: Planned[] = [];
    if (targeted) {
      const names = new Set<string>(),
        ids = new Set<string>();
      let leadTargets = 0;
      for (const choice of choices) {
        if (
          !choice.targets?.length ||
          !['anthropic', 'codex', 'opencode'].includes(choice.providerId)
        )
          return unavailable('Every supported model check must retain its member destination.');
        for (const target of choice.targets) {
          const row =
            target.kind === 'lead'
              ? leads[0]
              : view.members.find(
                  (member) =>
                    member.role === 'member' &&
                    member.label === (target.originalName ?? target.name)
                );
          const name = target.kind === 'lead' ? row?.label : target.name;
          if (
            (row && !row.selected) ||
            (!row && (target.kind !== 'member' || target.originalName !== undefined))
          )
            return unavailable('The original model check member is unavailable.');
          const memberId = row?.memberId ?? `draft:${name}`;
          if (!name || names.has(name) || ids.has(memberId))
            return unavailable('The model check member mapping is ambiguous.');
          names.add(name);
          ids.add(memberId);
          if (target.kind === 'lead') {
            leadTargets++;
            if (request.providerId !== undefined && request.providerId !== choice.providerId)
              return unavailable('The selected lead provider does not match its model check.');
          }
          const changedTeamWorkspace =
            resolve(leads[0]!.selected!.workspace) !== resolve(request.cwd);
          if (
            target.kind === 'member' &&
            row?.selected &&
            changedTeamWorkspace &&
            row.selected.workspaceInherited === undefined
          )
            return unavailable('The original member workspace source is unavailable.');
          const workspace =
            target.kind === 'lead' || !row?.selected || row.selected.workspaceInherited === true
              ? request.cwd
              : row.selected.workspace;
          const needsDraft =
            isDefaultProviderModelSelection(choice.model) ||
            (choice.effort === undefined && row?.selected?.effort !== undefined) ||
            !row?.selected ||
            providerId(row.selected.provider) !== choice.providerId ||
            resolve(row.selected.workspace) !== resolve(workspace);
          const draft = !needsDraft
            ? undefined
            : {
                providerId: choice.providerId as 'anthropic' | 'codex' | 'opencode',
                target:
                  target.kind === 'lead'
                    ? { kind: 'lead' as const }
                    : {
                        kind: 'member' as const,
                        name: target.name,
                        ...(target.originalName === undefined
                          ? {}
                          : { originalName: target.originalName }),
                      },
                workspace,
              };
          planned.push({
            memberId,
            saved: row?.selected ?? undefined,
            choice,
            ...(draft ? { draft } : {}),
          });
        }
      }
      // Existing dialogs prepare one provider at a time; a member-only provider
      // plan proves only those selected models, never whole-roster validity.
      if (leadTargets > 1)
        return unavailable('The model checks contain an ambiguous lead destination.');
    } else {
      for (const member of members) {
        const saved = member.selected!;
        const providerChoices = choices.filter(
          (choice) => choice.providerId === providerId(saved.provider)
        );
        const matches =
          providerChoices.length <= 1
            ? providerChoices
            : providerChoices.filter(
                (check) =>
                  (isDefaultProviderModelSelection(check.model) || check.model === saved.model) &&
                  (check.effort === undefined || check.effort === saved.effort)
              );
        if (choices.length > 0 && matches.length !== 1)
          return unavailable(
            'The edited models need an explicit member mapping before they can be checked.'
          );
        const choice = matches[0];
        const reset =
          choice &&
          (isDefaultProviderModelSelection(choice.model) ||
            (choice.effort === undefined && saved.effort !== undefined));
        planned.push({
          memberId: member.memberId,
          saved,
          choice,
          ...(reset
            ? {
                draft: {
                  providerId: providerId(saved.provider) as 'anthropic' | 'codex' | 'opencode',
                  target:
                    member.role === 'lead'
                      ? { kind: 'lead' as const }
                      : { kind: 'member' as const, name: member.label },
                  workspace: saved.workspace,
                },
              }
            : {}),
        });
      }
    }
    if (
      request.providerIds?.some(
        (id) =>
          !planned.some(
            (row) =>
              (row.choice?.providerId ?? (row.saved && providerId(row.saved.provider))) === id
          )
      )
    )
      return unavailable('The selected providers do not match the original dialog choices.');
    const represented = new Set<string>();
    const selected: BackendLaunchModelSelection[] = [];
    for (const row of planned) {
      const { choice, saved, draft } = row;
      if (choice) represented.add(checkKey(choice));
      const desiredProvider = choice?.providerId ?? (saved && providerId(saved.provider));
      const model = draft
        ? choice!.model
        : !choice || isDefaultProviderModelSelection(choice.model)
          ? saved!.model
          : choice.model;
      const effort = choice ? choice.effort : saved?.effort;
      if (
        desiredProvider === 'anthropic' &&
        (effort === 'none' || effort === 'minimal' || effort === 'ultra')
      )
        return unavailable('The selected effort is not supported by this captured member.');
      const context =
        desiredProvider !== 'anthropic'
          ? undefined
          : request.limitContext === undefined
            ? draft
              ? undefined
              : saved?.context
            : request.limitContext
              ? 'model-default'
              : 'one-million';
      if (
        !draft &&
        (!saved!.capabilities.includes('model') ||
          (effort !== undefined && !saved!.capabilities.includes('effort')) ||
          (context !== undefined && !saved!.capabilities.includes('context')))
      )
        return unavailable('The selected options are not supported by this captured member.');
      selected.push({
        launchId: view.launch.launchId,
        rosterRevision: view.launch.rosterRevision,
        memberId: row.memberId,
        model,
        ...(draft ? { draft } : {}),
        ...(effort === undefined ? {} : { effort }),
        ...(context === undefined ? {} : { context }),
      });
    }
    if (choices.some((choice) => !represented.has(checkKey(choice))))
      return unavailable('Some selected model checks have no Team member destination.');
    for (const selection of selected) {
      if (!alive()) throw new Error('Team context changed.');
      const rootId = commandId(handle, selection);
      const retained =
        request.preparationId && options.intents
          ? await options.intents.read(rootId, request.preparationId)
          : { commandId: rootId, retained: true };
      let id = retained.commandId;
      if (!alive()) throw new Error('Team context changed.');
      active.set(id, selection);
      let result = await invoke('read', selection, id);
      if (!alive()) throw new Error('Team context changed.');
      if (request.preparationId && options.intents) {
        const proof =
          result.ok && result.value && 'expiresAt' in result.value && 'model' in result.value
            ? (result.value as BackendLaunchModelProbe)
            : null;
        let invalidatedReleased = false;
        if (
          !retained.retained &&
          ((!result.ok && result.code === 'conflict') || proof?.phase === 'held')
        ) {
          // An explicit preparation may retire an invalidated or held original.
          // Confirmed cancellation requires released custody and grants no authority;
          // a replacement still needs fresh control admission and a model request.
          const original = await invoke('cancel', selection, id);
          if (!alive()) throw new Error('Team context changed.');
          invalidatedReleased =
            original.ok &&
            original.value !== null &&
            'expiresAt' in original.value &&
            'model' in original.value &&
            (original.value.phase === 'completed' || original.value.phase === 'cancelled');
        }
        const renew =
          !retained.retained &&
          (invalidatedReleased ||
            (proof !== null &&
              (proof.phase === 'completed' || proof.phase === 'cancelled') &&
              (!proof.ok || proof.expiresAt <= Date.now())));
        const admittedId = await options.intents.admit(rootId, request.preparationId, id, renew);
        if (!alive()) throw new Error('Team context changed.');
        if (admittedId !== id) {
          active.delete(id); // Only a proven released terminal check may be replaced.
          id = admittedId;
          active.set(id, selection);
          result = await invoke('read', selection, id);
          if (!alive()) throw new Error('Team context changed.');
        }
      }
      if (!result.ok)
        return unavailable('The original Team model check is unavailable. It was not resubmitted.');
      if (result.value === null) {
        // Current Host durable absence proves this exact intent has not been admitted.
        result = await invoke('start', selection, id);
      }
      const deadline = Date.now() + 100000;
      for (;;) {
        if (!alive()) throw new Error('Team context changed.');
        if (
          !result.ok ||
          !result.value ||
          !('expiresAt' in result.value) ||
          !('model' in result.value)
        )
          return unavailable(
            'The original Team model check outcome is unknown. Refresh reads the same check.'
          );
        const probe = result.value as BackendLaunchModelProbe;
        if (probe.phase !== 'running') {
          active.delete(id);
          if (probe.phase !== 'completed' || !probe.ok || probe.expiresAt <= Date.now())
            return unavailable(
              probe.phase === 'completed' && probe.expiresAt <= Date.now()
                ? 'The previous Team model check expired. An explicit new check is required.'
                : 'The captured Team model check did not succeed.'
            );
          completed.push(probe);
          break;
        }
        active.set(id, selection);
        if (Date.now() >= deadline) {
          throw new Error('The original Team model check timed out.');
        }
        await wait();
        if (!alive()) throw new Error('Team context changed.');
        result = await invoke('read', selection, id);
      }
    }
    const after = await readConfiguration();
    if (
      configurationFingerprint(after) !== configurationFingerprint(view) ||
      completed.some((probe) => probe.expiresAt <= Date.now())
    )
      return unavailable('The captured Team selection or model evidence changed during preflight.');
    return {
      ready: true,
      ...(request.preparationId && completed.length === selected.length
        ? {
            capturedTeamReadiness: {
              handleId: handle.handleId,
              preparationId: request.preparationId,
              launchId: view.launch.launchId,
              rosterRevision: view.launch.rosterRevision,
              selectionSignature: capturedTeamSelectionSignature({
                cwd: request.cwd,
                selectedModelChecks: choices,
                limitContext: request.limitContext,
              }),
              expiresAt: Math.min(...completed.map((probe) => probe.expiresAt)),
            },
          }
        : {}),
      message: 'Captured Team model checks passed.',
      details: [
        'Selected member accounts and model options were checked through the captured Host. No team member sessions were started.',
      ],
    };
  } catch {
    // Do not expose private descriptor/native errors in the existing dialog.
    return unavailable(
      alive()
        ? 'The captured Team model check is unavailable. Its original intent is retained.'
        : 'Team context changed.'
    );
  } finally {
    // Any unsettled original check must be cleaned before a failed preflight returns,
    // including roster-only conflicts while the foreground handle remains current.
    // Completed checks were removed; cleanup never redirects to another handle/ID.
    await Promise.allSettled(
      [...active.entries()].map(([id, selection]) => invoke('cancel', selection, id))
    );
  }
}
