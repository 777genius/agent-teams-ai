/**
 * Browser-safe custom team template contracts.
 *
 * `schemaVersion` is the contract version for the persisted custom template
 * record. It is deliberately separate from:
 * - the SQLite `PRAGMA user_version` owned by the internal storage layer, and
 * - any future portable profile file format version.
 *
 * Keep this module free of Node.js, Electron, SQLite and main-process imports.
 */
export const CUSTOM_TEAM_TEMPLATE_SCHEMA_VERSION = 1;

export type CustomTeamTemplateSchemaVersion = typeof CUSTOM_TEAM_TEMPLATE_SCHEMA_VERSION;

/**
 * Allowlisted per-member content.
 *
 * Only `name`, `role` and `workflow` may survive projection into a template.
 * Provider/model preferences, MCP policy, isolation, cwd, ids, timestamps and
 * removal markers are never part of the persisted template.
 */
export interface CustomTeamTemplateMemberV1 {
  name: string;
  role?: string;
  workflow?: string;
}

/**
 * Canonical, allowlisted template content.
 *
 * This is the exact payload a future save confirms and persists, with no team
 * identity, no project path, no runtime settings and no timestamps. It is the
 * input to deterministic canonical serialization and content equality.
 */
export interface CustomTeamTemplateContentV1 {
  schemaVersion: CustomTeamTemplateSchemaVersion;
  /** Team-level instructions. An empty string represents a template without a prompt. */
  teamPrompt: string;
  /** Ordered allowlisted members. Order participates in canonical content. */
  members: readonly CustomTeamTemplateMemberV1[];
}

/**
 * Internal custom team template record.
 *
 * Identity and presentation fields (`templateId`, `name`, `description`) are
 * supplied or generated by the trusted layer that owns the saved record; they
 * are kept separate from the allowlisted team content.
 */
export interface CustomTeamTemplateV1 extends CustomTeamTemplateContentV1 {
  /** Stable template identity. Later phases derive it from canonical content. */
  templateId: string;
  /** Display name. Original capitalization is preserved for display. */
  name: string;
  description?: string;
  /** Creation timestamp for the saved record, when the store supports one. */
  createdAt?: string;
  /**
   * Optimistic-concurrency revision for the saved record, when the store
   * stamps one. Absent means `1`; the create-team-from-template draft mapping
   * surfaces it as read-only metadata and never carries it into a new team.
   */
  revision?: number;
}
